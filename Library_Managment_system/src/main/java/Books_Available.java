       DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);

    String url = "jdbc:sqlserver://DESKTOP-IDGTE1B\\SQLEXPRESS;databaseName=Library Managment System;encrypt=true;trustServerCertificate=true";
    String user = "sa";
    String pwd = "taha2007";
    String query = "SELECT * FROM Booktbl";
    
    try (Connection conn = DriverManager.getConnection(url, user, pwd);
         Statement stm = conn.createStatement();
         ResultSet rs = stm.executeQuery(query)) {
        
        while(rs.next()) {
            String bookid = rs.getString("Book_id");
            String category = rs.getString("Categories"); // Fixed: Categories not Catagories
            String name = rs.getString("Book_Name");      // Fixed: Book_Name not "Book Name"
            String author = rs.getString("Author");
            int copies = rs.getInt("Copies");
            int author_id =rs.getInt("author_id");
            
            model.addRow(new Object[]{bookid, category, name, author, copies,author_id});
        }
        
        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "No books found in database");
        }
        
    } catch(SQLException e) {
        JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
           // This prints the full error to Output window
    }
