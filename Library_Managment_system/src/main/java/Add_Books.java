    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
         String id = jTextField1.getText().trim();
    String category = jTextField2.getText().trim();
    String name = jTextField3.getText().trim();
    String author = jTextField4.getText().trim();
    String copiesText = jTextField5.getText().trim();
    
    if(id.isEmpty() || category.isEmpty() || name.isEmpty() || author.isEmpty() || copiesText.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill all fields");
        return;
    }
    
    int copies;
    try {
        copies = Integer.parseInt(copiesText);
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Copies must be a number");
        return;
    }
    
    String url = "jdbc:sqlserver://DESKTOP-IDGTE1B\\SQLEXPRESS;databaseName=Library Managment System;encrypt=true;trustServerCertificate=true";
    String user = "sa";
    String pwd = "taha2007";
    try (Connection conn = DriverManager.getConnection(url, user, pwd)) {
        
        String checkSql = "SELECT Copies FROM Booktbl WHERE Book_id = ?";
        PreparedStatement checkPst = conn.prepareStatement(checkSql);
        checkPst.setString(1, id);
        ResultSet rs = checkPst.executeQuery();
        
        if(rs.next()) {
            int existingCopies = rs.getInt("Copies");
            int newTotal = existingCopies + copies;
            
            String updateSql = "UPDATE books SET Copies = ? WHERE Book_id = ?";
            PreparedStatement updatePst = conn.prepareStatement(updateSql);
            updatePst.setInt(1, newTotal);
            updatePst.setString(2, id);
            updatePst.executeUpdate();
            
            JOptionPane.showMessageDialog(this, "Book exists. Copies updated to " + newTotal);
            
        } else {
            String insertSql = "INSERT INTO Booktbl (Book_id, Categories, Book_Name, Author, Copies) VALUES (?,?,?,?,?)";
            PreparedStatement insertPst = conn.prepareStatement(insertSql);
            insertPst.setString(1, id);
            insertPst.setString(2, category);
            insertPst.setString(3, name);
            insertPst.setString(4, author);
            insertPst.setInt(5, copies);
            insertPst.executeUpdate();
            
            JOptionPane.showMessageDialog(this, "New book added successfully");
        }
        
        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");
        jTextField4.setText("");
        jTextField5.setText("");
        this.depose();
    } catch(SQLException e) {
        JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
    }   
        
    }//GEN-LAST:event_jButton1ActionPerformed

